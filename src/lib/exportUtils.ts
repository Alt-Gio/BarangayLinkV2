// BUDGET REPORT EXPORT
// ============================================

export const exportBudgetReport = (
  budgetData: {
    totalBudget: number;
    totalSpent: number;
    projectBudgets: any[];
  },
  format: 'pdf' | 'excel'
) => {
  const columns = [
    { header: 'Project', dataKey: 'title', key: 'title', width: 30 },
    { header: 'Department', dataKey: 'department', key: 'department', width: 20 },
    { header: 'Budget', dataKey: 'budgetFormatted', key: 'budgetFormatted', width: 15 },
    { header: 'Spent', dataKey: 'spentFormatted', key: 'spentFormatted', width: 15 },
    { header: 'Remaining', dataKey: 'remainingFormatted', key: 'remainingFormatted', width: 15 },
    { header: 'Utilization', dataKey: 'utilizationFormatted', key: 'utilizationFormatted', width: 12 }
  ];
  
  const formattedData = budgetData.projectBudgets.map(project => ({
    ...project,
    budgetFormatted: `₱${(project.budget || 0).toLocaleString()}`,
    spentFormatted: `₱${(project.spent || 0).toLocaleString()}`,
    remainingFormatted: `₱${((project.budget || 0) - (project.spent || 0)).toLocaleString()}`,
    utilizationFormatted: `${project.budget > 0 ? ((project.spent / project.budget) * 100).toFixed(1) : 0}%`
  }));
  
  if (format === 'pdf') {
    const doc = new jsPDF('landscape', 'mm', 'a4');
    
    // Title
    doc.setFontSize(20);
    doc.setTextColor(16, 185, 129);
    doc.text('Budget Report', 14, 20);
    
    // Summary
    doc.setFontSize(12);
    let y = 30;
    doc.text(`Total Budget: ₱${budgetData.totalBudget.toLocaleString()}`, 14, y);
    doc.text(`Total Spent: ₱${budgetData.totalSpent.toLocaleString()}`, 14, y + 7);
    doc.text(`Remaining: ₱${(budgetData.totalBudget - budgetData.totalSpent).toLocaleString()}`, 14, y + 14);
    doc.text(`Overall Utilization: ${budgetData.totalBudget > 0 ? ((budgetData.totalSpent / budgetData.totalBudget) * 100).toFixed(1) : 0}%`, 14, y + 21);
    
    // Table
    autoTable(doc, {
      startY: y + 30,
      head: [columns.map(col => col.header)],
      body: formattedData.map(item => columns.map(col => item[col.dataKey] || '-')),
      theme: 'grid',
      headStyles: { fillColor: [16, 185, 129] }
    });
    
    doc.save(`Budget_Report_${new Date().toISOString().split('T')[0]}.pdf`);
  } else {
    const wb = XLSX.utils.book_new();
    
    // Summary sheet
    const summary = [
      ['Budget Report Summary'],
      ['Generated', new Date().toLocaleString('en-PH')],
      [''],
      ['Total Budget', `₱${budgetData.totalBudget.toLocaleString()}`],
      ['Total Spent', `₱${budgetData.totalSpent.toLocaleString()}`],
      ['Remaining', `₱${(budgetData.totalBudget - budgetData.totalSpent).toLocaleString()}`],
      ['Utilization Rate', `${budgetData.totalBudget > 0 ? ((budgetData.totalSpent / budgetData.totalBudget) * 100).toFixed(1) : 0}%`]
    ];
    const summaryWs = XLSX.utils.aoa_to_sheet(summary);
    XLSX.utils.book_append_sheet(wb, summaryWs, 'Summary');
    
    // Details sheet
    const detailsWs = XLSX.utils.json_to_sheet(formattedData);
    XLSX.utils.book_append_sheet(wb, detailsWs, 'Project Budgets');
    
    XLSX.writeFile(wb, `Budget_Report_${new Date().toISOString().split('T')[0]}.xlsx`);
  }
};
