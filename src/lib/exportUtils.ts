export const exportAnalyticsReport = (
  analyticsData: {
    totalProjects: number;
    completedProjects: number;
    activeProjects: number;
    pendingProjects: number;
    totalBudget: number;
    completedBudget: number;
    departmentStats: any[];
    teamStats: any[];
    recentCompletions: any[];
  },
  format: 'pdf' | 'excel'
) => {
  const date = new Date().toLocaleDateString('en-PH');
  
  if (format === 'pdf') {
    const doc = new jsPDF('portrait', 'mm', 'a4');
    
    // Title
    doc.setFontSize(24);
    doc.setTextColor(16, 185, 129);
    doc.text('Analytics Report', 14, 20);
    
    // Summary
    doc.setFontSize(12);
    doc.setTextColor(100, 100, 100);
    doc.text(`Report Date: ${date}`, 14, 30);
    
    // Key Metrics
    doc.setFontSize(14);
    doc.setTextColor(0, 0, 0);
    doc.text('Key Performance Indicators', 14, 45);
    
    doc.setFontSize(10);
    let y = 55;
    doc.text(`Total Projects: ${analyticsData.totalProjects}`, 20, y);
    doc.text(`Completed: ${analyticsData.completedProjects} (${((analyticsData.completedProjects / analyticsData.totalProjects) * 100).toFixed(1)}%)`, 20, y + 7);
    doc.text(`Active: ${analyticsData.activeProjects}`, 20, y + 14);
    doc.text(`Pending: ${analyticsData.pendingProjects}`, 20, y + 21);
    doc.text(`Total Budget: ₱${analyticsData.totalBudget.toLocaleString()}`, 20, y + 28);
    doc.text(`Budget Utilization: ₱${analyticsData.completedBudget.toLocaleString()} (${analyticsData.totalBudget > 0 ? ((analyticsData.completedBudget / analyticsData.totalBudget) * 100).toFixed(1) : 0}%)`, 20, y + 35);
    
    // Department Performance
    if (analyticsData.departmentStats.length > 0) {
      autoTable(doc, {
        startY: y + 50,
        head: [['Department', 'Total', 'Active', 'Completed', 'Rate']],
        body: analyticsData.departmentStats.map(dept => [
          dept.name,
          dept.total.toString(),
          dept.active.toString(),
          dept.completed.toString(),
          `${dept.completionRate}%`
        ]),
        theme: 'grid',
        headStyles: { fillColor: [16, 185, 129] }
      });
    }
    
    doc.save(`Analytics_Report_${date.replace(/\//g, '-')}.pdf`);
  } else {
    // Excel export
    const wb = XLSX.utils.book_new();
    
    // Summary sheet
    const summaryData = [
      ['Analytics Report', ''],
      ['Generated', date],
      ['', ''],
      ['Metric', 'Value'],
      ['Total Projects', analyticsData.totalProjects],
      ['Completed Projects', analyticsData.completedProjects],
      ['Active Projects', analyticsData.activeProjects],
      ['Pending Projects', analyticsData.pendingProjects],
      ['Completion Rate', `${((analyticsData.completedProjects / analyticsData.totalProjects) * 100).toFixed(1)}%`],
      ['Total Budget', `₱${analyticsData.totalBudget.toLocaleString()}`],
      ['Completed Budget', `₱${analyticsData.completedBudget.toLocaleString()}`],
      ['Budget Utilization', `${analyticsData.totalBudget > 0 ? ((analyticsData.completedBudget / analyticsData.totalBudget) * 100).toFixed(1) : 0}%`]
    ];
    const summaryWs = XLSX.utils.aoa_to_sheet(summaryData);
    XLSX.utils.book_append_sheet(wb, summaryWs, 'Summary');
    
    // Department Performance sheet
    if (analyticsData.departmentStats.length > 0) {
      const deptWs = XLSX.utils.json_to_sheet(analyticsData.departmentStats);
      XLSX.utils.book_append_sheet(wb, deptWs, 'Departments');
    }
    
    // Team Performance sheet
    if (analyticsData.teamStats.length > 0) {
      const teamWs = XLSX.utils.json_to_sheet(analyticsData.teamStats);
      XLSX.utils.book_append_sheet(wb, teamWs, 'Team Performance');
    }
    
    XLSX.writeFile(wb, `Analytics_Report_${date.replace(/\//g, '-')}.xlsx`);
  }
};

